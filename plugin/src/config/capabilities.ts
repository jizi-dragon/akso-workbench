/**
 * 配置能力目录 —— **单一事实源**，与 `docs/reference/Akso平台内部API接口清单.md` 逐条对齐。
 *
 * 同一份数据同时驱动三处，避免"工具页写的"和"引擎执行的"是两套：
 *   1. host 引擎（plan/apply 按 capabilityId 找方法）；
 *   2. 工具页（列出全部接口、参数、请求示例、风险，便于审计与扩展）；
 *   3. 审计日志（记录本次操作对应哪个 capability）。
 *
 * 约定：
 *   - `path` 里的 `{xxx}` 是路径参数，从调用参数的 `xxx` 取；
 *   - 其余键都进请求体（GET 时进 query）；
 *   - `risk` 只描述**平台层面的影响**，不代表审批级别；
 *   - `irreversible` 为 true 的操作在 plan 里必须被标红；
 *   - `evidence` 对应文档里的标记：`verified` = ✅（抓包或验证环境跑通），
 *     `partial` = ⚠️（监听/推断，字段名或参数仍有不确定）。
 */

export type Domain =
  | 'auth'
  | 'object'
  | 'field'
  | 'picklist'
  | 'layout'
  | 'listlayout'
  | 'lifecycle'
  | 'workflow'
  | 'menu'
  | 'notice'

export type Risk = 'low' | 'medium' | 'high'

export type Evidence = 'verified' | 'partial'

export interface CapabilityParam {
  name: string
  location: 'path' | 'body' | 'query'
  required?: boolean
  type?: string
  description?: string
}

export interface Capability {
  id: string
  domain: Domain
  title: string
  description: string
  method: 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE'
  path: string
  risk: Risk
  irreversible?: boolean
  evidence: Evidence
  params: CapabilityParam[]
  /** 工具页的预填请求；引擎用同一形状生成 plan。少数接口（如菜单排序）整份 body 就是数组。 */
  example: Record<string, unknown> | unknown[]
  /** `data` 的形态，工具页直接展示，省得每次翻文档。 */
  returns?: string
  /** 文档「要点」里的坑，展示在卡片展开区。 */
  notes?: string[]
}

const p = (name: string, location: CapabilityParam['location'], required = true, type = 'string', description = ''): CapabilityParam => ({
  name,
  location,
  required,
  type,
  description,
})

