type Dict = Record<string, string>

let translate: (key: string, vars?: Record<string, string | number>) => string = (key) => key

/** `apply` 拿到 `ctx.locale.bind(NS)` 后注入进来 —— 组件里就有一份「读当前语言」的函数。 */
export function setTranslator(fn: (key: string, vars?: Record<string, string | number>) => string): void {
  translate = fn
}

/** 极简插值：`{name}`。 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const template = translate(key)
  if (vars === undefined) return template
  return template.replace(/\{(\w+)\}/g, (_m, name: string) => String(vars[name] ?? `{${name}}`))
}

